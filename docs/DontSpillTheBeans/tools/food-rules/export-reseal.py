"""Writes DSTB_Compat_Reseal.lua: which opened jars can be resealed, and into which closed jar.

    python docs/DontSpillTheBeans/tools/food-rules/export-reseal.py

Reads the recipes that open jars (the ones that hand the lid back: OnCreate RecipeCodeOnCreate.applyLidCondition, or
Base.JarLid among the outputs) of the game and of every mod below, takes the pairs of their itemMapper ("<open jar> = <closed jar>") and writes
them as Config.Reseal (open -> closed) and Config.SealedJars (the closed ones, which never spill). Ids of mods that are
not installed are harmless. Add a source below for another mod that opens jars the same way.
"""
import glob, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build as fb

OUT = os.path.join(os.path.dirname(fb.CONFIG), 'DSTB_Compat_Reseal.lua')

SOURCES = [('Project Zomboid', [fb.GAME + 'scripts/**/*.txt'])]
SOURCES.append(('Vanilla Foods Expanded (3577903007)', [fb.MODS['VFE']['scripts'][0].replace('/items/*.txt', '/**/*.txt')]))
SOURCES.append(('Long Term Preservation Extended (3597673472)', [g.replace('/media/scripts/**/*.txt', '/media/scripts/recipes/*.txt')
                                                              for g in fb.MODS['LTPE']['scripts']]))


def recipes(path):
    t = open(path, encoding='utf8', errors='ignore').read()
    module = re.search(r'module\s+(\w+)', t)
    module = module.group(1) if module else 'Base'
    for m in re.finditer(r'craftRecipe\s+(\w+)\s*\{', t):
        i, depth = m.end(), 1
        while depth and i < len(t):
            depth += (t[i] == '{') - (t[i] == '}')
            i += 1
        yield module + '.' + m.group(1), t[m.end():i - 1]


def opens_jar(body):
    """A recipe that opens a jar hands the lid back: either through applyLidCondition (the game's way) or as an output item."""
    outputs = re.search(r'outputs\s*\{(.*?)\}', body, re.S)
    return 'applyLidCondition' in body or bool(outputs and 'Base.JarLid' in outputs.group(1))


def opens_tin(body):
    """A recipe that opens a tin: the game's own ones finish with RecipeCodeOnCreate.openCan or openAndEat."""
    return 'RecipeCodeOnCreate.openCan' in body or 'RecipeCodeOnCreate.openAndEat' in body


def pairs(body):
    m = re.search(r'itemMapper\s+\w+\s*\{(.*?)\}', body, re.S)
    return re.findall(r'([\w.]+)\s*=\s*([\w.]+)', m.group(1)) if m else []


def main():
    found, tins = {}, {}
    # A mod may add its own jars and tins to the game's opening recipes with a partial override of the same name (Vanilla Foods
    # Expanded does), which carries the mapper but not what marks the recipe as one that opens a jar or a tin: the name tells.
    kinds = {}
    for title, globs in SOURCES:
        for g in globs:
            for f in glob.glob(g, recursive=True):
                for name, body in recipes(f):
                    if opens_jar(body):
                        kinds[name] = 'jar'
                    elif opens_tin(body):
                        kinds[name] = 'tin'
    for title, globs in SOURCES:
        n = 0
        for g in globs:
            for f in glob.glob(g, recursive=True):
                for name, body in recipes(f):
                    kind = kinds.get(name)
                    if not kind:
                        continue
                    for opened, closed in pairs(body):
                        if kind == 'tin':
                            tins[opened] = closed
                        else:
                            found[opened] = (closed, name)
                        n += 1
        print(f'{title}: {n} jars and tins')
    lines = ['-- Opened jars that can be resealed, and the closed jar each one came from: Config.Reseal (open -> closed) and',
             '-- Config.SealedJars (the closed ones, which never spill), and Config.OpenedTins (open tins, held while eaten from). Generated by',
             '-- docs/DontSpillTheBeans/tools/food-rules/export-reseal.py from the recipes that open jars (the game, Vanilla Foods Expanded and',
             '-- Long Term Preservation Extended); regenerate it instead of editing by hand. Ids of mods that are not installed are harmless.',
             '',
             'require "DSTB_Config"',
             '',
             'local Config = DontSpillTheBeans.Config',
             '',
             f'-- Open jar = {{ closed jar, the recipe that opens it (its animation is used for resealing) }} ({len(found)})',
             'local pairs_ = {']
    for opened in sorted(found):
        lines.append(f'    ["{opened}"] = {{ "{found[opened][0]}", "{found[opened][1]}" }},')
    lines += ['}', '', 'for opened, jar in pairs(pairs_) do', '    Config.Reseal[opened] = jar[1]', '    Config.ResealRecipe[opened] = jar[2]',
              '    Config.SealedJars[jar[1]] = true', 'end', '']
    lines += [f'-- Open tin = the closed tin it came from ({len(tins)}): the open ones are held while they are eaten from', 'local tins_ = {']
    for opened in sorted(tins):
        lines.append(f'    ["{opened}"] = "{tins[opened]}",')
    lines += ['}', '', 'for opened in pairs(tins_) do', '    Config.OpenedTins[opened] = true', 'end', '']
    open(OUT, 'w', encoding='utf8', newline='\n').write('\n'.join(lines))
    print(f'{len(found)} jar pairs, {len(tins)} tin pairs -> {os.path.basename(OUT)}')


if __name__ == '__main__':
    main()
