"""Turns a progress file saved by containers-<Key>.html into a compat module for the mod.

    python export-containers.py <progress.json> <Suffix> "<Source name>" <workshop id | vanilla> [out.lua]

Writes DSTB_Compat_<Suffix>_Containers.lua. Marks: open / sealed / whenfull (fluid containers) and
protective / plain (bags). Every marked item is set explicitly, replacing whatever the hand-written defaults in
DSTB_Config.lua said for it. Unmarked items keep the default behaviour.
"""
import json, os, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..'))
SHARED = os.path.join(REPO, 'mods/DontSpillTheBeans/42/media/lua/shared')


def block(ids):
    lines, cur = [], '   '
    for i in ids:
        piece = f' "{i}",'
        if len(cur) + len(piece) > 118:
            lines.append(cur)
            cur = '   '
        cur += piece
    if cur.strip():
        lines.append(cur)
    return '\n'.join(lines)


def main():
    progress, suffix, source, workshop = sys.argv[1:5]
    out = sys.argv[5] if len(sys.argv) > 5 else os.path.join(SHARED, f'DSTB_Compat_{suffix}_Containers.lua')
    marks = json.load(open(progress, encoding='utf8'))
    fizzy = marks.pop('__fizzy', {}) or {}   # id -> true / false: carbonated drinks that foam over
    groups = {m: sorted(k for k, v in marks.items() if v == m) for m in ('open', 'sealed', 'whenfull', 'protective', 'plain')}
    sections = ''.join(f'\n-- {title} ({len(groups[m])})\nrule("{m}", {{\n{block(groups[m])}\n}})\n'
                       for m, title in (('open', 'Open fluid containers'), ('sealed', 'Sealed fluid containers'),
                                        ('whenfull', 'Sealed while full'), ('protective', 'Bags that shield liquids'),
                                        ('plain', 'Plain bags')) if groups[m])
    fizz_yes = sorted(k for k, v in fizzy.items() if v is True)
    fizz_no = sorted(k for k, v in fizzy.items() if v is False)
    if fizz_yes or fizz_no:
        sections += f'\n-- Carbonated drinks, which foam over when opened after exercise ({len(fizz_yes)} yes, {len(fizz_no)} marked not)\ncarbonated(true, {{\n{block(fizz_yes)}\n}})\ncarbonated(false, {{\n{block(fizz_no)}\n}})\n'
    text = f'''-- {source} ({workshop}): how its fluid containers and bags behave when carried.
-- Generated by docs/DontSpillTheBeans/tools/food-rules/export-containers.py from {os.path.basename(progress)};
-- regenerate it instead of editing by hand. Ids for items that are not installed are harmless.

require "DSTB_Config"

local Config = DontSpillTheBeans.Config

-- Marks drinks as carbonated, or clears the mark.
local function carbonated(yes, ids)
    for _, id in ipairs(ids) do Config.CarbonatedItems[id] = yes or nil end
end

-- Sets exactly one rule per id, overriding any earlier (default or other-file) entry for it.
local function rule(name, ids)
    for _, id in ipairs(ids) do
        Config.OpenFluidItems[id], Config.SealedFluidItems[id], Config.SealedWhenFull[id] = nil, nil, nil
        if name == "open" then Config.OpenFluidItems[id] = true
        elseif name == "sealed" then Config.SealedFluidItems[id] = true
        elseif name == "whenfull" then Config.SealedWhenFull[id] = true
        elseif name == "protective" then Config.ProtectiveContainers[id] = true
        elseif name == "plain" then Config.ProtectiveContainers[id] = nil
        end
    end
end
{sections}'''
    open(out, 'w', encoding='utf8', newline='\n').write(text)
    print('wrote', out, {m: len(v) for m, v in groups.items()})


if __name__ == '__main__':
    sys.exit(main())
