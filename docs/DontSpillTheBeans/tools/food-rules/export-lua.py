"""Turns a progress file saved by food-rules-<Key>.html into a compat module for the mod.

    python export-lua.py <progress.json> <Suffix> "<Mod name>" <workshop id | vanilla> [out.lua]

Writes DSTB_Compat_<Suffix>.lua (default: the mod's shared lua folder). Marks: "exempt" = always exempt,
"whole" = exempt while uneaten, "spill" = follows the normal rules. Every marked id is set explicitly, replacing any
earlier entry for it. "spill" marks need no entry (nothing is exempt by default), so they are not written.
"""
import json, os, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..'))
SHARED = os.path.join(REPO, 'mods/DontSpillTheBeans/42/media/lua/shared')


def block(ids):
    lines, cur = [], '   '
    for i in ids:
        piece = f' "{i}",'
        if len(cur) + len(piece) > 118:
            lines.append(cur)
            cur = '   '
        cur += piece
    if cur.strip():
        lines.append(cur)
    return '\n'.join(lines)


def main():
    args = sys.argv[1:]
    progress, suffix, mod, workshop = args[:4]
    out = args[4] if len(args) > 4 else os.path.join(SHARED, f'DSTB_Compat_{suffix}.lua')
    marks = json.load(open(progress, encoding='utf8'))
    liquid = marks.pop('__liquid', {}) or {}   # id -> true / false: liquidy foods that wet as well as stain
    groups = {m: sorted(k for k, v in marks.items() if v == m) for m in ('exempt', 'whole', 'spill')}
    sections = [('exempt', 'Always exempt'), ('whole', 'Exempt while uneaten')]
    body = ''.join(f'\n-- {title} ({len(groups[m])})\nrule("{m}", {{\n{block(groups[m])}\n}})\n' for m, title in sections if groups[m])
    liquid_yes = sorted(k for k, v in liquid.items() if v is True)
    liquid_no = sorted(k for k, v in liquid.items() if v is False)
    if liquid_yes or liquid_no:
        body += f'\n-- Liquidy foods: soups, stews... ({len(liquid_yes)} yes, {len(liquid_no)} marked not liquid)\nliquid(true, {{\n{block(liquid_yes)}\n}})\nliquid(false, {{\n{block(liquid_no)}\n}})\n'
    text = f'''-- {mod} ({workshop}): which of its foods are exempt from the loose-food mechanic.
-- Generated by docs/DontSpillTheBeans/tools/food-rules/export-lua.py from {os.path.basename(progress)};
-- regenerate it instead of editing by hand. Ids for items that are not installed are harmless.
-- Closed cans/jars and foods with no nutrition are handled by rule and are not listed.

require "DSTB_Config"

local Config = DontSpillTheBeans.Config

-- Marks foods as liquidy (they wet what they spill on, not just stain it), or clears the mark.
local function liquid(yes, ids)
    for _, id in ipairs(ids) do Config.LiquidFoods[id] = yes or nil end
end

-- Sets exactly one rule per id, replacing any earlier (default or other-file) entry for it.
local function rule(name, ids)
    for _, id in ipairs(ids) do
        Config.FoodExempt[id], Config.FoodExemptWhenUneaten[id] = nil, nil
        if name == "exempt" then Config.FoodExempt[id] = true
        elseif name == "whole" then Config.FoodExemptWhenUneaten[id] = true
        end
    end
end
{body}'''
    open(out, 'w', encoding='utf8', newline='\n').write(text)
    print('wrote', out, '|', {m: len(v) for m, v in groups.items()}, '(spill marks need no entry)')


if __name__ == '__main__':
    sys.exit(main())
