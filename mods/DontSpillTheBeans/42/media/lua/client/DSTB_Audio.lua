-- Sounds. Client only: nothing here is a sound the zombies can hear (no world noise is made).
--   * moving with something spilled in a carried bag: the contents shuffle (dry food, liquid, liquid-flagged food), each
--     kind its own sound, layered, and its volume following how much of it is in the bags. The cadence, the volume model and
--     the way other players are heard are Dynamic Gear Rattling's (Workshop 3808152720, credit it on the Workshop page):
--     a timer counted in ticks per movement state, a volume factor per state, a random variation, quieter when zoomed out;
--     other players' sounds are played at their position, their bag contents being relayed by the server.
--   * the "Empty Spilled Contents" action, a hot spill that burns, a drink that foams over: one-shots (DSTB_Audio.event).
-- The sound script and its files are generated by scripts/master-audio.py (sounds DSTB_<Name>, and DSTB_<Name>M, the muffled
-- variants). The game's own hearing filters (Deaf, Hard of Hearing) are FMOD event parameters, which sounds
-- made of loose files never see, so they are handled here, for the listener: deaf hears nothing; hard of hearing hears the muffled variants (a low-pass baked into the file).

require "DSTB_Config"
require "DSTB_Wet"
require "DSTB_Options"
require "DSTB_Carried"

local DSTB = DontSpillTheBeans
local Config = DSTB.Config

local Audio = {}
DSTB.Audio = Audio

-- Options (Options > Mods). Missing PZAPI (old game build): everything at full volume.
local options, sliders = DSTB.Options.page, {}
local function addSlider(id, label)
    if options then sliders[id] = options:addSlider(id, label, 0, 100, 1, 100) end
end
if options then
    options:addTitle("Sound volume")
    options:addDescription("0 to 100, default 100. The sounds of spilled contents shuffling in a bag are always quieter than the clothing rattles of Dynamic Gear Rattling.")
    addSlider("MasterVolume", "Master volume")
    addSlider("WalkVolume", "Spilled contents moving in a bag")
    addSlider("EventVolume", "Emptying, burns and foaming over")
end

local function level(id)
    local slider = sliders[id]
    return slider and slider:getValue() / 100 or 1
end

-- How the listener hears: nil = not at all (deaf), false = normally, true = muffled.
local function hearing(player)
    if player:hasTrait(CharacterTrait.DEAF) then return nil end
    return player:hasTrait(CharacterTrait.HARD_OF_HEARING)
end

-- Plays sound `name` (a DSTB_ sound without the muffled suffix) at `volume` (0..1) for the local player `listener`: on their
-- own emitter, or, when `source` (another player) is given, at that player's position; always the muffled variant if
-- `muffle` is set. Returns the Audio and the volume it was started at, or nil.
local function play(listener, name, volume, source, muffle)
    local muffled = hearing(listener)
    if muffled == nil then return nil end
    muffled = muffled or muffle
    volume = volume * level("MasterVolume")
    if volume <= 0.001 then return nil end
    name = name .. (muffled and "M" or "")
    local audio
    if source then
        audio = getSoundManager():PlayWorldSoundImpl(name, false, math.floor(source:getX()), math.floor(source:getY()), math.floor(source:getZ()), 1, 0, volume, true)
    else
        audio = getSoundManager():PlaySound(name, false, volume)
    end
    if audio then audio:setVolume(volume) end
    return audio, volume
end

-- A one-shot (name without the DSTB_ prefix, e.g. "Burn"): at the events volume.
function Audio.event(player, name)
    return play(player, "DSTB_" .. name, level("EventVolume"))
end

-- Fades the sounds in `entries` (the { audio, volume } list of Audio.emptying) in or out over `seconds` (mode "in" / "out"),
-- starting after `delay` seconds; fading out ends by stopping them. A sound that has finished or been stopped is never
-- touched again (the game hands its emitter to the next sound, which must be left alone).
function Audio.fade(entries, seconds, mode, delay)
    local live = {}
    for _, e in ipairs(entries) do
        if not e.done then live[#live + 1] = e end
    end
    if #live == 0 then return end
    local from = getTimestampMs() + (delay or 0) * 1000
    if mode == "in" then
        for _, e in ipairs(live) do e.audio:setVolume(0) end
    end
    local step
    step = function()
        local f = (getTimestampMs() - from) / 1000 / seconds
        if f < 0 then return end
        f = math.min(1, f)
        for _, e in ipairs(live) do
            if not e.done then
                if not e.audio:isPlaying() then
                    e.done = true
                elseif mode == "out" then
                    e.out = true
                    if f >= 1 then e.audio:stop(); e.done = true else e.audio:setVolume(e.volume * (1 - f) * (1 - f)) end
                elseif not e.out then
                    e.audio:setVolume(e.volume * f * f)
                end
            end
        end
        if f >= 1 then Events.OnTick.Remove(step) end
    end
    Events.OnTick.Add(step)
end

-- The sounds of emptying a bag, all at once and layered: the base sound always, and one per kind of spilled content the bag
-- holds. They are loops (they run as long as the action does), fade in as it starts, and are faded out by the caller
-- with Audio.fade(entries, ..., "out") when it ends; as a failsafe they fade out by themselves `seconds` + 3 s after
-- starting. Returns the list of { audio, volume }.
function Audio.emptying(player, bag, seconds)
    local amounts = DSTB.Wet.bagAmounts(bag)
    local started = {}
    local function add(name)
        local audio, volume = Audio.event(player, name)
        if audio then started[#started + 1] = { audio = audio, volume = volume } end
    end
    add("EmptyBase")
    if amounts.food > 0 then add("EmptyDry") end
    if amounts.liquid > 0 then add("EmptyLiquid") end
    if amounts.drink > 0 then add("EmptyWet") end
    Audio.fade(started, 0.15, "in")
    Audio.fade(started, 0.6, "out", seconds + 3)
    return started
end

-- 0..1 loudness factor for an amount of spilled contents; `full` is the amount that is the loudest.
local function amountFactor(amount, full)
    if amount <= 0 then return 0 end
    local min = Config.SoundMinFactor
    return min + (1 - min) * math.min(1, amount / full)
end

-- Movement states that never shuffle (not walking about).
local STILL = {
    bumped = true, falling = true, knockeddown = true, collide = true, getup = true, climbfence = true, climbwall = true,
    sitonground = true, sitonfurniture = true, onground = true, idle = true,
}

-- Ticks between two shuffles and the volume factor, by how the character moves (Dynamic Gear Rattling's values).
local BASE_WALK, BASE_RUN = 16, 13.5
local function pace(player)
    if player:isAiming() then
        return math.max(BASE_WALK - 4, BASE_WALK * 2 - player:getPerkLevel(Perks.Nimble) * 2 - 8), 0.85
    end
    local running, sneaking = player:isRunning(), player:isSneaking()
    local sprint = player:getPerkLevel(Perks.Sprinting) * 1.25 / 12
    if running and sneaking then return BASE_RUN + 1, 0.85 end
    if running then return BASE_RUN - sprint, 1.25 end
    if player:isSprinting() then return BASE_RUN - 1 - sprint, 1.4 end
    if sneaking then return 17, 0.75 end
    return BASE_WALK, 1
end

-- One player's shuffling for this update: `amounts` = { food, liquid, drink, nested = {...} } in their bags (the nested ones
-- are inside another bag and sound muffled), `source` = nil for the local player, else the other player the sound comes
-- from. Every kind present plays its own sound at the same moment, so any mix of dry food, liquid and liquid food layers.
-- For the local player `amounts` is nil: their bags are only looked at (Carried.get, kept for a second and refreshed the
-- moment the server reports a spill) when a step is actually due, and the volumes follow what is in them at that step.
local timers = {}   -- key -> ticks since the last shuffle

local function shuffle(listener, player, key, amounts, source)
    local t = math.min(100, (timers[key] or 0) + getGameTime():getMultiplier())
    timers[key] = t
    if t < 12 then return end   -- the shortest interval of all, nothing to check yet

    local state = player:getAnimationStateName()
    if STILL[state] or not (player:isPlayerMoving() or state == "climbwindow") then return end
    if player:isDriving() or player:getVehicle() or player:GetAnimSetName() == "player-vehicle" then return end
    local interval, speed = pace(player)
    if t < interval then return end
    timers[key] = 0

    amounts = amounts or DSTB.Carried.get(listener)
    local n = amounts.nested
    if amounts.food + amounts.liquid + amounts.drink + n.food + n.liquid + n.drink <= 0 then return end

    local zoom = 1 - getCore():getZoom(listener:getPlayerNum()) / 6
    local walk = level("WalkVolume") * speed * zoom
    for _, sound in ipairs({
        { "DryWalk", amounts.food, n.food, Config.SoundFullFood },
        { "LiquidWalk", amounts.liquid, n.liquid, Config.SoundFullLiquid },
        { "WetWalk", amounts.drink, n.drink, Config.SoundFullDrink },
    }) do
        local direct, inside = amountFactor(sound[2], sound[4]), amountFactor(sound[3], sound[4])
        if direct > 0 then play(listener, "DSTB_" .. sound[1], direct * walk * (1 - ZombRand(1, 20) / 100), source) end
        if inside > 0 then play(listener, "DSTB_" .. sound[1], inside * walk * (1 - ZombRand(1, 20) / 100), source, true) end
    end
end

-- What the other players carry, relayed by the server (it alone sees their inventories): online id -> { food, liquid, drink }.
local remote = {}
local MAX_DISTANCE = 10     -- tiles: other players further away are not played at all
local REASK_TICKS = 1800     -- updates between two requests for everybody's state
local sinceAsk = REASK_TICKS

function Audio.setRemote(args)
    if type(args.id) == "number" then
        remote[args.id] = { food = args.food or 0, liquid = args.liquid or 0, drink = args.drink or 0,
            nested = { food = args.nfood or 0, liquid = args.nliquid or 0, drink = args.ndrink or 0 } }
    end
end

local function onPlayerUpdate(player)
    if not player:isLocalPlayer() or not DSTB.isEnabled() then return end

    shuffle(player, player, "local" .. player:getPlayerNum(), nil, nil)

    -- Other players (multiplayer): those within earshot whose bags hold something.
    if player:getPlayerNum() ~= 0 then return end
    local online = getOnlinePlayers()
    if not online or online:size() < 2 then return end
    local unknown = false
    for i = 0, online:size() - 1 do
        local other = online:get(i)
        if other ~= player and not other:isLocalPlayer() then
            local state = remote[other:getOnlineID()]
            if not state then
                unknown = true
            elseif state.food + state.liquid + state.drink + state.nested.food + state.nested.liquid + state.nested.drink > 0
                and IsoUtils.DistanceTo(player:getX(), player:getY(), other:getX(), other:getY()) <= MAX_DISTANCE then
                shuffle(player, other, "remote" .. other:getOnlineID(), state, other)
            end
        end
    end
    -- Somebody whose state never reached this client (they were here before we joined): ask for everybody's.
    if unknown then
        sinceAsk = sinceAsk + 1
        if sinceAsk >= REASK_TICKS then
            sinceAsk = 0
            sendClientCommand(player, DSTB.MODULE, "soundRequest", {})
        end
    end
end

Events.OnPlayerUpdate.Add(onPlayerUpdate)
